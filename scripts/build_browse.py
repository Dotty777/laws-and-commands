"""Build GitHub-readable indexes from the verified current catalogue."""

from collections import Counter, defaultdict
from html import escape
import argparse
import json
import posixpath
from pathlib import Path, PurePosixPath
import re
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
BROWSE = "browse"
ROWS_PER_PAGE = 75
MAX_PAGE_BYTES = 150_000
GENERATED = "<!-- Generated by scripts/build_browse.py. -->\n\n"
TYPE_ORDER = (
    ("Law", "law", "Standing law or provision"),
    ("Command", "command", "Direct charge or prohibition"),
    ("Commission", "commission", "An entrusted role or task"),
    ("Instruction", "instruction", "Practical conduct or procedure"),
    ("Wisdom", "wisdom", "Counsel, maxim, or teaching illustration"),
    ("Study Context", "study-context", "Background or comparison"),
    ("Mixed", "mixed", "Several types without one dominant type"),
)
AUDIT_GROUP = "70-book audit"


def read(path):
    return json.loads((ROOT / path).read_text(encoding="utf-8"))


def md(value):
    value = escape(" ".join(str(value).split()), quote=False)
    return re.sub(r"([\\|\[\]*_~\x60])", r"\\\1", value)


def link(label, target):
    return f"[{md(label)}]({target})"


def local(source, target, label, fragment=""):
    rel = posixpath.relpath(target, posixpath.dirname(source))
    return link(label, rel + ("#" + fragment if fragment else ""))


def table(headers, rows):
    yield "| " + " | ".join(headers) + " |"
    yield "| " + " | ".join("---:" if h in {"Records", "No."} else "---" for h in headers) + " |"
    for row in rows:
        yield "| " + " | ".join(map(str, row)) + " |"


def page(lines):
    return GENERATED + "\n".join(lines).rstrip() + "\n"


def safe_slug(value):
    if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", value):
        raise ValueError(f"Unsafe directory name: {value}")
    return value


def safe_reference_url(value, prefix):
    url = urlsplit(value)
    if url.scheme != "https" or url.netloc != "saints.bible" or not url.path.startswith(prefix):
        raise ValueError(f"Unexpected catalogue URL: {value}")
    if re.search(r"[\s()<>]", value):
        raise ValueError(f"Unsafe Markdown URL: {value}")
    return value


def anchor(record):
    return "record-" + record["id"].lower()


def group_path(dimension, slug):
    return f"{BROWSE}/{dimension}/{slug}/README.md"


def chunks(records):
    return [records[i:i + ROWS_PER_PAGE] for i in range(0, len(records), ROWS_PER_PAGE)]


def part_path(group_index, part):
    return f"{posixpath.dirname(group_index)}/part-{part:03d}.md"


def build():
    records = read("data/current/commands.json")
    summary = read("data/current/summary.json")
    books = read("source/translation/book-index.json")
    original = read("data/commands.json")
    archive = {r["id"]: (r["category"], r["record_file"]) for r in original}
    aliases = summary["merged_record_ids"]
    active_archive = set(archive) - aliases.keys()
    archive_topics = read("data/categories.json")
    if len(books) != summary["canonical_books"] or len(active_archive) != summary["archive_join"]["matched"]:
        raise ValueError("Book register or archival IDs do not match the catalogue summary")

    books_by_name = {b["book"]: safe_slug(b["slug"]) for b in books}
    types_by_name = {name: slug for name, slug, _ in TYPE_ORDER}
    topic_metadata = {t["category"]: t for t in archive_topics}
    topics_by_name = {name: safe_slug(PurePosixPath(t["file"]).stem) for name, t in topic_metadata.items()}
    topics_by_name[AUDIT_GROUP] = "70-book-audit"
    if any(len(set(g.values())) != len(g) for g in (books_by_name, types_by_name, topics_by_name)):
        raise ValueError("Colliding browse group paths")

    by_book, by_type, by_topic = (defaultdict(list) for _ in range(3))
    archived_joined = set()
    ids = set()
    source_link_count = 0
    for r in records:
        id_ = r["id"]
        if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9-]*", id_) or id_.lower() in ids:
            raise ValueError(f"Missing, unsafe, or duplicate record ID: {id_}")
        ids.add(id_.lower())
        safe_reference_url(r["catalogue_url"], "/instructions/")
        safe_reference_url(r["scripture_url"], "/bible/")
        for extra in r["additional_scripture"]:
            safe_reference_url(extra["url"], "/bible/")
            source_link_count += 1
        prior = r["archived_record_id"]
        if prior:
            if prior != id_ or prior not in archive:
                raise ValueError(f"Invalid archive join: {id_}")
            topic = archive[prior][0]
            if r["topic"] and r["topic"] != topic:
                raise ValueError(f"Current topic disagrees with archive topic for {id_}")
            archived_joined.add(prior)
        elif r["collection"] == AUDIT_GROUP:
            topic = AUDIT_GROUP
        elif r["topic"] in topic_metadata:
            topic = r["topic"]
        else:
            raise ValueError(f"No topic grouping for current-only record {id_}")
        by_book[r["book"]].append(r)
        by_type[r["record_type"]].append(r)
        by_topic[topic].append(r)

    if (len(records) != summary["records"] or source_link_count != summary["additional_scripture_links"]
            or list(by_book) != list(books_by_name) or set(by_type) != set(types_by_name)
            or set(by_topic) != set(topics_by_name) or archived_joined != active_archive
            or {k: len(v) for k, v in by_book.items()} != summary["books"]
            or {k: len(v) for k, v in by_type.items()} != summary["record_types"]):
        raise ValueError("Browse groups do not match the current catalogue")
    archived_topics = defaultdict(Counter)
    for r in original:
        if r["id"] in active_archive:
            archived_topics[r["category"]][r["audience"]] += 1
    for name in topic_metadata:
        if Counter(r["audience"] for r in by_topic[name] if r["archived_record_id"]) != archived_topics[name]:
            raise ValueError(f"Archive-backed topic counts disagree for {name}")

    files = {}
    book_home = {}
    for name, items in by_book.items():
        index = group_path("books", books_by_name[name])
        parts = chunks(items)
        for i, part in enumerate(parts, start=1):
            path = index if len(parts) == 1 else part_path(index, i)
            book_home.update((r["id"], path) for r in part)

    type_book_home = defaultdict(dict)
    type_book_count = defaultdict(Counter)
    for name, slug, _ in TYPE_ORDER:
        index = group_path("record-types", slug)
        parts = chunks(by_type[name])
        for i, part in enumerate(parts, start=1):
            path = index if len(parts) == 1 else part_path(index, i)
            for r in part:
                book = r["book"]
                type_book_home[name].setdefault(book, (path, r["id"]))
                type_book_count[name][book] += 1

    def type_book_link(path, name, book, label):
        target, _ = type_book_home[name][book]
        return local(path, target, label, "book-" + books_by_name[book])

    def main_nav(path):
        return " · ".join(local(path, target, label) for target, label in (
            ("browse/README.md", "Browse home"),
            ("browse/books/README.md", "All books"),
            ("browse/record-types/README.md", "All Record types"),
            ("browse/categories/README.md", "All topics"),
        ))

    def record_row(path, r, dimension):
        ref = link(r["reference"], r["scripture_url"])
        if dimension == "books" and r["additional_scripture"]:
            ref += "<br>Also: " + ", ".join(link(s["reference"], s["url"]) for s in r["additional_scripture"])
        id_label = chr(96) + r["id"] + chr(96)
        if dimension == "books":
            title = f'<a name="{anchor(r)}"></a>' + link(r["title"], r["catalogue_url"]) + "<br>" + id_label
            prior = r["archived_record_id"]
            if prior:
                archive_file = archive[prior][1]
                if not archive_file.startswith("categories/") or not (ROOT / archive_file).is_file():
                    raise ValueError(f"Missing archive record page: {prior}")
                title += " · " + local(path, archive_file, "Archive", prior)
            type_label = type_book_link(path, r["record_type"], r["book"], r["record_type"])
            return (title, ref, type_label, md(r["origin"]), md(r["audience"]))
        title = local(path, book_home[r["id"]], r["title"], anchor(r)) + "<br>" + id_label
        book = local(path, group_path("books", books_by_name[r["book"]]), r["book"])
        if dimension == "record-types":
            if type_book_home[r["record_type"]][r["book"]][1] == r["id"]:
                title = f'<a name="book-{books_by_name[r["book"]]}"></a>' + title
            return (title, ref, book, md(r["origin"]), md(r["audience"]))
        type_label = type_book_link(path, r["record_type"], r["book"], r["record_type"])
        if dimension == "torah-law":
            return (title, ref, md(r["original_audience_or_recipient"]), md(r["origin"]))
        return (title, ref, book, type_label, md(r["audience"]))

    def render_group(dimension, name, slug, items, caption):
        index = group_path(dimension, slug)
        parts = chunks(items)
        headings = {
            "books": ("Study record", "Scripture", "Record type", "Origin", "Filing"),
            "record-types": ("Study record", "Scripture", "Book", "Origin", "Filing"),
            "categories": ("Study record", "Scripture", "Book", "Record type", "Filing"),
            "torah-law": ("Torah Law", "Scripture", "Original audience", "Origin"),
        }[dimension]
        lines = [f"# {md(name)}", "", main_nav(index), "", f"**{len(items):,} current study records.** {caption}", ""]
        if dimension == "books":
            lines += ["**Jump by Record type:** " + " · ".join(
                type_book_link(index, kind, name, f"{kind} ({type_book_count[kind][name]:,})")
                for kind, _, _ in TYPE_ORDER if name in type_book_home[kind]
            ), ""]
        if dimension == "record-types":
            lines += ["## Jump to a book", ""]
            for testament, register in (("Old Testament", books[:43]), ("New Testament", books[43:])):
                links = [
                    type_book_link(index, name, b["book"], f'{b["book"]} ({type_book_count[name][b["book"]]:,})')
                    for b in register if b["book"] in type_book_home[name]
                ]
                if links:
                    lines += [f"**{testament}:** " + " · ".join(links), ""]
            lines += ["## " + ("Records" if len(parts) == 1 else "All parts"), ""]
        if dimension == "categories" and name in topic_metadata:
            lines += [local(index, topic_metadata[name]["file"], "Open the original topic archive"), ""]
        if len(parts) == 1:
            lines += list(table(headings, (record_row(index, r, dimension) for r in items)))
        else:
            lines += list(table(("Page", "Records", "First reference", "Last reference"), (
                (local(index, part_path(index, i), f"Part {i}"), len(part), md(part[0]["reference"]), md(part[-1]["reference"]))
                for i, part in enumerate(parts, start=1)
            )))
            for i, part in enumerate(parts, start=1):
                path = part_path(index, i)
                nav = []
                if i > 1:
                    nav.append(local(path, part_path(index, i - 1), "Previous part"))
                nav.append(local(path, index, "All parts"))
                if i < len(parts):
                    nav.append(local(path, part_path(index, i + 1), "Next part"))
                nav_line = " · ".join(nav)
                first, last = (i - 1) * ROWS_PER_PAGE + 1, (i - 1) * ROWS_PER_PAGE + len(part)
                part_lines = [f"# {md(name)}: part {i} of {len(parts)}", "", main_nav(path), "", nav_line, "",
                              f"Records {first:,}–{last:,} of {len(items):,}.", ""]
                part_lines += list(table(headings, (record_row(path, r, dimension) for r in part)))
                part_lines += ["", nav_line]
                files[path] = page(part_lines)
        files[index] = page(lines)

    hub = "browse/README.md"
    files[hub] = page([
        "# Browse the current Saints.Bible catalogue", "",
        f"**{len(records):,} study records** across **{len(books):,} books**, including **{source_link_count:,} additional Scripture links**.", "",
        "- " + local(hub, "browse/books/README.md", "By book") + " — read in the Saints.Bible book and passage order.",
        "- " + local(hub, "browse/record-types/README.md", "By Record type") + " — browse all seven types.",
        "- " + local(hub, "browse/torah-law/README.md", "Torah Law") + " — browse the reviewed standing provisions in Exodus through Deuteronomy.",
        "- " + local(hub, "browse/categories/README.md", "By topic") + " — browse the original topic groupings with current records, plus the 70-book audit additions.", "",
        "The type and topic views link to the same record in its book. The book view includes primary and additional Scripture references. The Filing column shows whether the catalogue lists the record under General or Personal.", "",
        local(hub, "README.md", "Repository home") + " · " + local(hub, "README.md", "Original category archive", "archival-import-and-category-index") + " · " +
        local(hub, summary["workbook"]["path"], "Download the workbook"),
    ])

    book_index = "browse/books/README.md"
    files[book_index] = page(["# Browse by book", "", main_nav(book_index), "",
        "Books follow the Saints.Bible order. Each record has its own link within the book view.", "",
        *table(("No.", "Book", "Records"), (
            (i, local(book_index, group_path("books", b["slug"]), b["book"]), len(by_book[b["book"]]))
            for i, b in enumerate(books, start=1)
        )),
    ])
    for name, slug in books_by_name.items():
        render_group("books", name, slug, by_book[name], "Use the Scripture column to open the passage, or follow a study title to Saints.Bible.")

    type_index = "browse/record-types/README.md"
    files[type_index] = page(["# Browse by Record type", "", main_nav(type_index), "",
        "Record type describes the material in the study record. Origin, audience, and application are separate fields.", "",
        *table(("Record type", "Records", "Meaning"), (
            (local(type_index, group_path("record-types", slug), name), len(by_type[name]), md(meaning))
            for name, slug, meaning in TYPE_ORDER
        )),
    ])
    for name, slug, meaning in TYPE_ORDER:
        render_group("record-types", name, slug, by_type[name], meaning + ". Select a study title to open its entry in the book view.")

    topic_index = "browse/categories/README.md"
    files[topic_index] = page(["# Browse by topic", "", main_nav(topic_index), "",
        f"The {len(archive_topics)} original topic groups show {len(active_archive):,} active archival records alongside reviewed additions with matching topics. "
        f"The 70-book audit group contains {len(by_topic[AUDIT_GROUP]):,} records whose Topic field holds their Record type.", "",
        *table(("Topic or collection", "Records"), (
            (local(topic_index, group_path("categories", slug), name), len(by_topic[name]))
            for name, slug in topics_by_name.items()
        )),
    ])
    for name, slug in topics_by_name.items():
        caption = "Select a study title to open its entry in the book view."
        if name == AUDIT_GROUP:
            caption = "These records were added after the original archive and are also listed by book and Record type."
        render_group("categories", name, slug, by_topic[name], caption)
    torah_index = "browse/torah-law/README.md"
    torah = {name: [r for r in by_book[name] if r["study_placement"] == "Torah Law"]
             for name in ("Exodus", "Leviticus", "Numbers", "Deuteronomy")}
    count = sum(map(len, torah.values()))
    if count != summary["torah_laws"]:
        raise ValueError("Torah Law counts disagree")
    files[torah_index] = page(["# Torah Law", "", main_nav(torah_index), "",
        f"**{count:,} records tagged Torah Law.** The catalogue counts distinct standing provisions within their original scope.",
        "", *table(("Book", "Records"), ((local(torah_index, group_path("torah-law", books_by_name[b]), b), len(rows))
                                         for b, rows in torah.items())),
        "", local(torah_index, "audit/torah-law/README.md", "Audit method and merge index"),
    ])
    for name, items in torah.items():
        render_group("torah-law", name, books_by_name[name], items, "Select a title to see all sources in its book view.")
    if len(book_home) != len(records):
        raise ValueError("Missing canonical book record target")
    if any(len(content.encode("utf-8")) > MAX_PAGE_BYTES for content in files.values()):
        raise ValueError("A generated page exceeds the GitHub reading size limit")
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify generated files without changing the repository")
    args = parser.parse_args()
    files = build()
    browse = (ROOT / BROWSE).resolve()
    existing = {p.relative_to(ROOT).as_posix(): p for p in (ROOT / BROWSE).rglob("*.md")}
    obsolete = set(existing) - files.keys()
    changed = [name for name, content in files.items()
               if name not in existing or existing[name].read_bytes() != content.encode("utf-8")]
    if args.check:
        if obsolete or changed:
            parser.error(f"Browse output differs: {len(changed)} missing or changed, {len(obsolete)} obsolete. Run scripts/build_browse.py.")
    else:
        for name in set(changed) | obsolete:
            path = ROOT / name
            if not path.resolve().is_relative_to(browse) or (path.exists() and not path.read_bytes().startswith(GENERATED.encode())):
                parser.error(f"Refusing to replace a file outside the generated browse set: {name}")
        for name in obsolete:
            existing[name].unlink()
        for name in changed:
            path = ROOT / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(files[name].encode("utf-8"))
    print(f"{'Verified' if args.check else 'Built'} {len(files):,} pages for book, Record type, and topic browsing.")


if __name__ == "__main__":
    main()
